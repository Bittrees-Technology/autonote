import sharp from 'sharp';
import { readFile, writeFile } from 'node:fs/promises';
const icon = await readFile(new URL('../app/icon.svg', import.meta.url));
await sharp(icon).resize(180,180).png().toFile(new URL('../app/apple-icon.png', import.meta.url).pathname);
const sizes=[16,32,48];
const images=await Promise.all(sizes.map(size=>sharp(icon).resize(size,size).png().toBuffer()));
const header=Buffer.alloc(6+16*sizes.length); header.writeUInt16LE(1,2); header.writeUInt16LE(sizes.length,4);
let offset=header.length;
images.forEach((buffer,i)=>{const p=6+16*i; header[p]=sizes[i];header[p+1]=sizes[i];header.writeUInt16LE(1,p+4);header.writeUInt16LE(32,p+6);header.writeUInt32LE(buffer.length,p+8);header.writeUInt32LE(offset,p+12);offset+=buffer.length;});
await writeFile(new URL('../app/favicon.ico',import.meta.url),Buffer.concat([header,...images]));
await sharp(new URL('./assets/social-preview.svg',import.meta.url).pathname).png().toFile(new URL('../public/social-preview.png',import.meta.url).pathname);
